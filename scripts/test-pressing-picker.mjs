import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as jsx from 'react/jsx-runtime';
import * as icons from 'lucide-react';
import * as THREE from 'three';
import postcss from 'postcss';
const compile = file => ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText;
const presets = {};
vm.runInNewContext(compile('src/features/identity/pressing-rings.ts'), { exports: presets, require: () => THREE });
function tree(open, disabled = false) {
  const calls = [];
  let state = 0;
  const hooks = { useState: () => [state++ === 0 ? open : presets.PRESSING_PRESETS.findIndex(item=>item.id==='triple'), value => calls.push(value)], useEffect() {}, useId: () => 'preset', useRef: () => ({ current: { focus() {} } }) };
  const exports = {};
  vm.runInNewContext(compile('src/features/identity/PressingPresetPicker.tsx'), { exports, require: name => name === 'react' ? hooks : name === 'react/jsx-runtime' ? jsx : name === 'lucide-react' ? icons : presets });
  const element = exports.PressingPresetPicker({ value: 'triple', disabled, marksEnabled: true, onChange: value => calls.push(value), onMarksChange: value => calls.push(['marks',value]), onSleeveMaterialChange: value=>calls.push(['material',value]) });
  return { element, calls };
}
const closed = tree(false);
const presetAnchor = closed.element.props.children[1];
assert.equal(presetAnchor.props.className,"dc-pressing-select");
const trigger = presetAnchor.props.children[0];
assert.equal(trigger.type, 'button');
assert.equal(trigger.props['aria-haspopup'], 'listbox');
assert.equal(trigger.props['aria-expanded'], false);
trigger.props.onKeyDown({ key: 'ArrowDown', preventDefault() {} });
assert.equal(closed.calls.at(-1), true);
const opened = tree(true);
const list = opened.element.props.children[1].props.children[1];
assert.equal(list.props.role, 'listbox');
assert.equal(list.props.children.length, presets.PRESSING_PRESETS.length);
assert.equal(list.props.children[presets.PRESSING_PRESETS.findIndex(item=>item.id==='triple')].props['aria-selected'], true);
list.props.onKeyDown({ key: 'Enter', preventDefault() {} });
assert.equal(opened.calls[0], 'triple');
let stopped = false;
list.props.onKeyDown({ key: 'Escape', preventDefault() {}, stopPropagation() { stopped = true; } });
assert.ok(stopped, 'Escape closes menu without closing preview');
assert.equal(tree(true, true).element.props.children[1].props.children[1], false);
const marksLabel=closed.element.props.children[2];
assert.equal(marksLabel.type,'label');
const marksInput=marksLabel.props.children[0];
assert.equal(marksInput.props.type,'checkbox');
assert.equal(marksInput.props.checked,true);
marksInput.props.onChange({target:{checked:false}});
assert.deepEqual(closed.calls.at(-1),['marks',false]);
assert.equal(tree(false,true).element.props.children[2].props.children[0].props.disabled,true,'Marks cannot change during sharing');
const paperSelect=closed.element.props.children[3].props.children[1];
assert.equal(closed.element.props.children[3].props.children[0],'Sleeve material');
assert.equal(paperSelect.props.value,'printed-board','Preview defaults to Printed Cardboard');
paperSelect.props.onChange({target:{value:'matte'}});
assert.deepEqual(closed.calls.at(-1),['material','matte']);
assert.equal(tree(false,true).element.props.children[3].props.children[1].props.disabled,true);
assert.deepEqual(Array.from(paperSelect.props.children,option=>option.props.value),['printed-board','printed-board-glossy','matte']);
const preview = readFileSync('src/features/identity/Sleeve3DPreview.tsx', 'utf8');
assert.match(preview, /createPortal\(\s*<PressingPresetPicker/);
assert.match(preview, /camera.add\(viewerLight, viewerLight.target\)/);
assert.doesNotMatch(preview, /<select/);
assert.doesNotMatch(preview, /useState<PressingPreset>/, 'Preset is not reset by dialog remount');
assert.match(preview, /useRef<PressingPreset>\(pressingPreset\)/, 'Reopened geometry starts with retained preset');
const editor = readFileSync('src/features/identity/DesignConfiguratorEditor.tsx', 'utf8');
assert.match(editor, /pressingPreset=\{pressingPreset\}/);
assert.match(editor, /onPressingPresetChange=\{setPressingPreset\}/);
const settings=editor.slice(editor.indexOf('{dialog === "settings"'));
assert.ok(settings.indexOf('Sleeve windows')<settings.indexOf('<span>Sleeve material</span>'));
assert.ok(settings.indexOf('<span>Sleeve material</span>')<settings.indexOf('Print dimensions'));
const selectionCode=editor.slice(editor.indexOf('  const [previewSleeveMaterial,'),editor.indexOf('  const [sleevePreviewLabels,'));
let override=null, lastSetting;
const materialContext={design:{sleeveMaterial:'printed-board'},
  useState:()=>[override,value=>{override=value;}],
  useEffect:(effect,[setting])=>{if(setting!==lastSetting){lastSetting=setting;effect();}},
};
vm.createContext(materialContext);
vm.runInContext(ts.transpileModule(`function selection(){${selectionCode}\nreturn {material:previewSleeveMaterial ?? design.sleeveMaterial ?? "printed-board",select:setPreviewSleeveMaterial};}`,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,materialContext);
const selection=()=>{materialContext.selection();return materialContext.selection();};
assert.equal(selection().material,'printed-board');
selection().select('matte');
assert.equal(selection().material,'matte','Preview material can differ from Settings');
assert.equal(materialContext.design.sleeveMaterial,'printed-board','Preview leaves the project print material intact');
materialContext.design.sleeveMaterial='printed-board-glossy';
assert.equal(selection().material,'printed-board-glossy','Settings changes override a temporary preview choice');
selection().select('matte');
materialContext.design.sleeveMaterial='printed-board';
assert.equal(selection().material,'printed-board','Undoing Settings also restores the authoritative material');
const previewAst=ts.createSourceFile('Sleeve3DPreview.tsx',preview,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
let paperInitializer;
function findPaper(node) {
  if(ts.isVariableDeclaration(node) && node.name.getText(previewAst)==='classicPaper') paperInitializer=node.initializer;
  ts.forEachChild(node,findPaper);
}
findPaper(previewAst);
assert.ok(paperInitializer && ts.isConditionalExpression(paperInitializer));
assert.equal(paperInitializer.condition.getText(previewAst),'sleeveMaterial === "matte"');
assert.equal(paperInitializer.whenFalse.kind,ts.SyntaxKind.NullKeyword);
let loadsPaper=false;
function findPaperLoad(node) {
  if(ts.isCallExpression(node) && node.expression.getText(previewAst)==='loadClassicSleevePaper') loadsPaper=true;
  ts.forEachChild(node,findPaperLoad);
}
findPaperLoad(paperInitializer.whenTrue);
assert.ok(loadsPaper,'Matte selection loads classic paper, regardless of formatting or error handling');
const changeHandler = preview.slice(preview.indexOf('const changePressingPreset'), preview.indexOf('\n  return (', preview.indexOf('const changePressingPreset')));
