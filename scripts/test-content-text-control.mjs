import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import React from 'react';
const compile = file => ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.React } }).outputText;
const model = {};
vm.runInNewContext(compile('src/features/identity/design-configurator-model.ts'), { exports: model });
assert.equal(model.capitalizeWords('OTHER FREQUENCIES'), 'Other Frequencies');
assert.equal(model.capitalizeWords('árbol ÉXITO\n  strange-ANIMALS'), 'Árbol Éxito\n  Strange-Animals');
assert.equal(model.capitalizeWords("don't STOP"), "Don't Stop");
assert.equal(model.capitalizeWords('日本語 カタカナ'), '日本語 カタカナ');
assert.equal(model.capitalizeWords(''), '');
const controls = {};
vm.runInNewContext(compile('src/features/identity/ContentTextControl.tsx'), {
  exports: controls, React, require: name => name === 'react' ? { useId: () => 'content-test' } : model,
});
const nodes = node => !node || typeof node !== 'object' ? [] : Array.isArray(node) ? node.flatMap(nodes) : [node, ...nodes(node.props?.children)];
let capitalized, changed, commits = 0;
const props = { text: 'OTHER FREQUENCIES', onTransform: text => { capitalized = text; }, onChange: text => { changed = text; }, onCommit: () => { commits++; } };
const tree = nodes(controls.ContentTextControl(props));
const buttons = tree.filter(n => n.type === 'button');
assert.equal(buttons.length, 3);
const button = buttons[1];
assert.equal(button.props['aria-label'], 'Capitalize each word');
assert.equal(button.props.children, 'Aa');
button.props.onClick();
assert.equal(capitalized, 'Other Frequencies');
buttons[0].props.onClick();
assert.equal(capitalized, 'other frequencies');
const mixed = nodes(controls.ContentTextControl({ ...props, text: 'Árbol\nOther sounds' })).filter(n => n.type === 'button');
mixed[2].props.onClick();
assert.equal(capitalized, 'ÁRBOL\nOTHER SOUNDS');
mixed[0].props.onClick();
assert.equal(capitalized, 'árbol\nother sounds');
assert.ok(nodes(controls.ContentTextControl({ ...props, text: '   ' })).filter(n => n.type === 'button').every(n => n.props.disabled));
const textarea = tree.find(n => n.type === 'textarea');
assert.equal(tree.find(n => n.type === 'label').props.htmlFor, textarea.props.id);
textarea.props.onChange({ target: { value: 'new text' } });
assert.equal(changed, 'new text');
textarea.props.onBlur();
assert.equal(commits, 1);
assert.equal(nodes(controls.ContentTextControl({ ...props, text: '   ' })).find(n => n.type === 'button').props.disabled, true);
console.log('Content control: lowercase, title case, uppercase, Unicode, line breaks, editing and empty state passed.');
