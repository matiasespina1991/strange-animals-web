import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import React from 'react';
const compile = (file) => ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.React } }).outputText;
const model = {};
vm.runInNewContext(compile('src/features/identity/design-configurator-model.ts'), { exports: model });
const component = {};
vm.runInNewContext(compile('src/features/identity/ImageAppearanceControls.tsx'), { exports: component, React, require: () => model });
const nodes = node => !node || typeof node !== 'object' ? [] : Array.isArray(node) ? node.flatMap(nodes) : [node, ...nodes(node.props?.children)];
let patch;
const render = layer => nodes(component.ImageAppearanceControls({ layer, onChange: value => { patch = value; }, onCommit: () => {} }));
const base = { id: 'test', kind: 'image', name: 'asset', image: 'data:image/svg+xml;base64,abc' };
const barcode = render({ ...base, imageRole: 'barcode' });
assert.equal(barcode.filter(n => n.type === 'input' && n.props.type === 'checkbox').length, 0);
assert.equal(barcode.filter(n => n.type === 'input' && n.props.type === 'color').length, 2);
barcode.find(n => n.props?.['aria-label'] === 'Background').props.onChange({ target: { value: '#ff0000' } });
assert.equal(patch.imageBarBackground, '#ff0000');
barcode.find(n => n.props?.['aria-label'] === 'Crop top').props.onChange({ target: { value: 99 } });
assert.equal(patch.imageCrop.top, 45);
const svg = render(base);
assert.equal(svg.filter(n => n.type === 'input' && n.props.type === 'checkbox').length, 0);
assert.equal(svg.filter(n => n.type === 'input' && n.props.type === 'color').length, 1);
const logo = render({ ...base, imageRole: 'brand-logo' });
assert.equal(logo.filter(n => n.type === 'input' && n.props.type === 'checkbox').length, 1);
assert.equal(logo.filter(n => n.type === 'input' && n.props.type === 'color').length, 0);
console.log('Image appearance controls: role-specific options, background updates and crop bounds passed.');
