import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = readFileSync('src/features/identity/local-font-use-case.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const storage = new Map();
const window = { location: { hostname: 'localhost' }, localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) } };
const exports = {};
vm.runInNewContext(code, { window, exports });
assert.equal(exports.canUseLocalFontUseCase(), true);
exports.setLocalFontUseCase('sample', true);
assert.equal(exports.hasLocalFontUseCase('sample'), true);
exports.setLocalFontUseCase('sample', true);
assert.equal(JSON.parse([...storage.values()][0]).length, 1);
window.location.hostname = 'strangeanimals.de';
assert.equal(exports.hasLocalFontUseCase('sample'), false);
assert.equal(exports.canUseLocalFontUseCase(), false);
assert.throws(() => exports.setLocalFontUseCase('other', true));
window.location.hostname = 'localhost';
assert.equal(exports.hasLocalFontUseCase('sample'), true);
exports.setLocalFontUseCase('sample', false);
assert.equal(exports.hasLocalFontUseCase('sample'), false);
const serverExports = {};
vm.runInNewContext(code, { exports: serverExports });
assert.equal(serverExports.canUseLocalFontUseCase(), false);
console.log('Tattoo: localhost-only visibility, persistent assignment/removal, deduplication and non-browser safety passed.');
